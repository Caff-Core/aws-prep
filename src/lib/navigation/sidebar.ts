import type { StarlightRouteData } from '@astrojs/starlight/route-data';
import type { AvailableCertification } from '~/lib/certifications/schema';

type SidebarEntry = StarlightRouteData['sidebar'][number];
type SidebarLink = Extract<SidebarEntry, { type: 'link' }>;
type SidebarGroup = Extract<SidebarEntry, { type: 'group' }>;
type Pagination = StarlightRouteData['pagination'];

const CERTIFICATION_PATH = /^\/certifications\/([a-z0-9-]+)(?:\/|$)/;

export function certificationIdFromPath(pathname: string): string | undefined {
  return CERTIFICATION_PATH.exec(pathname)?.[1];
}

function findGroup(entries: SidebarEntry[], label: string): SidebarGroup | undefined {
  for (const entry of entries) {
    if (entry.type !== 'group') continue;
    if (entry.label === label) return entry;
    const nested = findGroup(entry.entries, label);
    if (nested) return nested;
  }
  return undefined;
}

/**
 * Narrows the global autogenerated sidebar to one certification. Module folders
 * are named by slug, so they are relabelled and ordered from certification data.
 * Keeping order in data means URLs never need numeric prefixes.
 */
export function scopeSidebar(
  sidebar: SidebarEntry[],
  certification: AvailableCertification,
): SidebarEntry[] {
  const root = findGroup(sidebar, certification.id);
  if (!root) return sidebar;

  const links = root.entries.filter((entry) => entry.type === 'link');
  const modules = certification.modules.flatMap((module) => {
    const group = root.entries.find(
      (entry) => entry.type === 'group' && entry.label === module.slug,
    );
    return group ? [{ ...group, label: module.title }] : [];
  });

  return [...links, ...modules];
}

function flatten(entries: SidebarEntry[]): SidebarLink[] {
  return entries.flatMap((entry) => (entry.type === 'link' ? [entry] : flatten(entry.entries)));
}

/** Previous and next links confined to the given sidebar. */
export function paginationFor(entries: SidebarEntry[]): Pagination {
  const links = flatten(entries);
  const index = links.findIndex((link) => link.isCurrent);
  if (index === -1) return { prev: undefined, next: undefined };
  return { prev: links[index - 1], next: links[index + 1] };
}

export function practiceLink(certificationId: string, pathname: string): SidebarLink {
  const href = `/certifications/${certificationId}/practice/`;
  return {
    type: 'link',
    label: 'Practice questions',
    href,
    isCurrent: pathname === href,
    badge: undefined,
    attrs: {},
  };
}

export function allCertificationsLink(): SidebarLink {
  return {
    type: 'link',
    label: 'All certifications',
    href: '/certifications/',
    isCurrent: false,
    badge: undefined,
    attrs: { class: 'sidebar-back-link' },
  };
}
